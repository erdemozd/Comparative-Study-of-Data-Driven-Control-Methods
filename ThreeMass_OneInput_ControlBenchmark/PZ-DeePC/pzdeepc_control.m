function [u0,info] = pzdeepc_control( ...
    uIni, ...
    yIni, ...
    rPreview, ...
    rDotPreview, ...
    p, ...
    ctrl)
% PZDEEPC_CONTROL
%
% Pole-informed DeePC with internally optimized steady input.
%
% Terminal constraints are imposed on the physical, unfiltered state.

%% 1. Inputs

uIni = uIni(:);
yIni = yIni(:);

rPreview = rPreview(:);
rDotPreview = rDotPreview(:); %#ok<NASGU>

p = p; %#ok<NASGU>

rTarget = ...
    rPreview(1);

%% 2. Desired physical equilibrium

xTarget = [ ...
    rTarget;
    0;
    rTarget;
    0;
    rTarget;
    0];

Xreference = ...
    kron( ...
    ones(ctrl.N,1), ...
    xTarget);

%% 3. Filter past trajectory

yIniPrime = ...
    pz_filter_past_output( ...
    yIni, ...
    ctrl.prior.polyCoeff, ...
    ctrl.ny);

%% 4. Physical inverse-filter offset

[Mcheck,dPast] = ...
    pz_unfilter_map( ...
    yIni, ...
    ctrl.prior.polyCoeff, ...
    ctrl.N, ...
    ctrl.ny);

if norm(Mcheck-ctrl.M,'fro') > 1e-10

    error( ...
        'PZ inverse-filter map mismatch.');

end

%% 5. Objective

stateErrorOffset = ...
    dPast ...
    - ...
    Xreference;

f = ...
    2*ctrl.Ax' ...
    *ctrl.Qbar ...
    *stateErrorOffset;

%% 6. Terminal equality RHS

terminalTarget = ...
    ctrl.ExTerm*xTarget;

terminalOffset = ...
    ctrl.Tx*dPast;

beq = [ ...
    uIni;
    yIniPrime;
    terminalTarget-terminalOffset;
    zeros(ctrl.nTerm,1)];

%% 7. Position bounds

positionOffset = ...
    ctrl.SqBar*dPast;

nPos = ...
    numel(positionOffset);

bposition = [ ...
    ctrl.qMax*ones(nPos,1) ...
    - ...
    positionOffset;
    ...
    ctrl.qMax*ones(nPos,1) ...
    + ...
    positionOffset];

bineq = [ ...
    ctrl.binput;
    bposition;
    ctrl.bsteadyInput];

%% 8. Solve

tic;

[z,J,exitflag,output] = ...
    quadprog( ...
    ctrl.H, ...
    f, ...
    ctrl.Aineq, ...
    bineq, ...
    ctrl.Aeq, ...
    beq, ...
    [], ...
    [], ...
    [], ...
    ctrl.opts);

solveTime = ...
    toc;

%% 9. Failure

if exitflag <= 0 || isempty(z)

    u0 = NaN;

    info.success = false;
    info.exitflag = exitflag;
    info.solveTime = solveTime;

    info.J = NaN;

    info.g = [];
    info.sigmaNorm = NaN;

    info.uPred = [];
    info.xPred = [];

    info.uSteady = NaN;

    info.output = output;

    return;

end

%% 10. Extract

g = ...
    z(ctrl.gIndex);

sigma = ...
    z(ctrl.sigmaIndex);

uSteady = ...
    z(ctrl.usIndex);

uPred = ...
    ctrl.Uf*g;

xPredVector = ...
    ctrl.Gx*g ...
    + ...
    dPast;

xPred = ...
    reshape( ...
    xPredVector, ...
    6, ...
    ctrl.N);

u0 = ...
    uPred(1);

%% 11. Return

info.success = true;
info.exitflag = exitflag;
info.solveTime = solveTime;

info.J = J;

info.g = g;
info.sigmaNorm = norm(sigma,2);

info.uPred = uPred;
info.xPred = xPred;

info.uSteady = uSteady;

info.output = output;

end